//! The commands that wait, as data: a program and the words that make its command destructive,
//! outward, or code the check cannot read. `../tests/commands.tsv` holds every spelling these
//! rows cover; a new spelling is added there first.
use super::super::Wait;

/// When a family's program makes its command wait. Arguments are compared after quotes, carets
/// and backslashes are removed.
pub(super) enum Rule {
    /// Every command of the program.
    Always,
    /// An argument equals one of the words, without case.
    Word(&'static [&'static str]),
    /// An argument equals one of the words as written.
    Exact(&'static [&'static str]),
    /// An argument starts with one of the words, without case.
    Prefix(&'static [&'static str]),
    /// An argument starts with one of the words as written.
    Starts(&'static [&'static str]),
    /// A single-dash option holds one of the letters, without case, alone or bundled.
    Bundle(&'static str),
    /// A word of the first list and a word of the second both appear, without case.
    Pair(&'static [&'static str], &'static [&'static str]),
    /// No argument other than options: the program reads its code from standard input.
    Bare,
    /// An argument has the `host:path` form.
    Remote,
    /// An argument holds a pattern that can name many files.
    Glob,
    /// Git's `-c name=value`, which can name a program for Git to run.
    Setting,
}

pub(super) struct Family {
    pub(super) names: &'static [&'static str],
    /// Name beginnings that belong to the family, such as `mkfs.ext4`.
    pub(super) stems: &'static [&'static str],
    pub(super) rules: &'static [Rule],
    pub(super) wait: Wait,
    /// The program runs what it is fed, so a download in the same command is run as code.
    pub(super) shell: bool,
}

const fn destructive(names: &'static [&'static str], rules: &'static [Rule]) -> Family {
    Family {
        names,
        stems: &[],
        rules,
        wait: Wait::Destructive,
        shell: false,
    }
}

const fn unread(names: &'static [&'static str], rules: &'static [Rule]) -> Family {
    Family {
        names,
        stems: &[],
        rules,
        wait: Wait::NotUnderstood,
        shell: false,
    }
}

const fn interpreter(names: &'static [&'static str], rules: &'static [Rule]) -> Family {
    Family {
        names,
        stems: &[],
        rules,
        wait: Wait::NotUnderstood,
        shell: true,
    }
}

