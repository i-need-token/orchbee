impl super::CliText {
    pub(crate) const fn cli_report_presentation_label(self) -> &'static str {
        match self.locale {
            Locale::EnUs => "Presentation",
            Locale::ZhCn => "终端成员",
        }
    }

    pub(crate) const fn cli_labels(self) -> &'static CliLabels {
        match self.locale {
            Locale::EnUs => &EN_US_LABELS,
            Locale::ZhCn => &ZH_CN_LABELS,
        }
    }

    pub(crate) const fn cli_current_presentation_label(self) -> &'static str {
        match self.locale {
            Locale::EnUs => "Current presentation",
            Locale::ZhCn => "当前终端成员",
        }
    }

    pub(crate) const fn cli_current_panel_label(self) -> &'static str {
        match self.locale {
            Locale::EnUs => "Current panel",
            Locale::ZhCn => "当前面板",
        }
    }
}
