impl Locale {
    /// Help and the action menu share the current Client's detach lifecycle wording.
    pub(super) const fn client_detach_label(self) -> &'static str {
        match self {
            Self::EnUs => "Leave view; terminals keep running",
            Self::ZhCn => "离开界面；终端继续运行",
        }
    }
}
